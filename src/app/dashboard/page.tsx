import Link from "next/link";
import { Suspense } from "react";
import { Shell } from "@/components/shell";
import { getDashboardWidgets } from "@/lib/scripting/dashboard-runtime";
import styles from "./mystic-theme.module.css";
import { listMysticBulletins } from "@/lib/mystic/native-bulletins";

export default function Dashboard() {
  return <Suspense fallback={<Shell active="/dashboard"><section className="panel">Loading dashboard...</section></Shell>}><DashboardContent /></Suspense>;
}

async function DashboardContent() {
  const widgets = await getDashboardWidgets();
  const bulletins = await listMysticBulletins();
  const bulletinSections = [...new Set(bulletins.map(item => item.section))];
  return <Shell active="/dashboard">
    {widgets.map((widget, index) => {
      if (widget.type === "welcome") return <details key={index} open className={styles.dashboardSection}><summary className={styles.collapseHeading}>Welcome</summary><header className={styles.hero}>
        <span className={styles.eyebrow}>MysticWeb · Scripted Dashboard</span>
        <h1>{widget.title}</h1><p>{widget.description}</p>
        <div className={styles.heroActions}><Link href="/messages">Explore message boards</Link><Link href="/files">Browse files</Link></div>
      </header></details>;
      if (widget.type === "bulletins") return <details key={index} open className={styles.dashboardSection}><summary className={styles.collapseHeading}>{widget.title}<span>{bulletins.length ? "From your Mystic BBS" : "Bulletin files unavailable"}</span></summary>
        <div className={styles.announcements}>
          {bulletinSections.map(section => <div key={section}><div className={styles.announcementHeader}>{section}</div>
            {bulletins.filter(item => item.section === section).map(item => <article key={item.id} className={styles.announcement}><h3><Link href={`/bulletins/${item.id}`}>{item.id}. {item.title}</Link></h3><p>{item.preview}</p><Link href={`/bulletins/${item.id}`}>Read full bulletin</Link></article>)}</div>)}
          {!bulletins.length && <p className={styles.announcement}>No bulletin entries or matching files were found in the configured Mystic bulletin menu.</p>}
        </div>
      </details>;
      if (widget.type === "stat") return <details key={index} open className={styles.dashboardSection}><summary className={styles.collapseHeading}>{widget.title}</summary><section className={styles.stat}>
        <span>{widget.title}</span><strong>{widget.value}</strong><span>{widget.description}</span>
      </section></details>;
      return <details key={index} open className={styles.dashboardSection}><summary className={styles.collapseHeading}>{widget.title}</summary><section className={styles.announcements} aria-label={widget.title}>
        <div className={styles.announcementHeader}>{widget.title}</div>
        <div className={styles.announcement}><p>{widget.description}</p>{widget.items.map((item,i)=><p key={i}>{item}</p>)}</div>
      </section></details>;
    })}
    <p className={styles.note}>The dashboard is generated by default-dashboard.js. Bulletins are read from the configured Mystic installation; other widgets are still placeholders.</p>
  </Shell>;
}
